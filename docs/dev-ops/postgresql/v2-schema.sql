-- V2 PostgreSQL 空库结构。来源：mysql/migrations/manifest.json（001—007）。
-- 三个逻辑库分别执行本脚本；每库包含全部表及 000—003 分表。
-- 幂等初始化，不负责修复已存在但定义不同的表，不包含旧 V1 结构。
-- JSON 使用 jsonb；原始消息使用 bytea；hash 保留 char(64)，不能重新序列化后重算。
-- MySQL datetime 映射为 UTC timestamp without time zone，避免事务开始时间冻结。
-- 所有文本采用 C 二进制排序。varchar 尾空格比较与 MySQL PAD SPACE 有差异，业务身份不得带尾空格。
-- active_key 按 V2 manifest 保留普通可空列，关闭案例由业务写 NULL；UNIQUE 允许多个 NULL。
-- manifest 的 V2 fresh 表没有 ON UPDATE 或生成列；旧 V1 的相关定义不属于本脚本。
-- AUTO_INCREMENT 使用 BY DEFAULT IDENTITY；显式导入 ID 后须同步 sequence，不保证连续号。
